#!/usr/bin/env python3
"""srcdiff -- find code in a published artifact that was never in the repository.

This is the xz-utils shape: the release tarball contained build machinery that
was not in the git tree, and nobody was diffing the two. The check is simple to
state and annoying to do well, because legitimate divergence is the *norm* --
generated files, vendored dependencies, packaging metadata, excluded tests. The
work is suppressing that without suppressing the one finding that matters.

Standard library only. No requests, no packaging, no diffoscope.

    srcdiff compare SDIST.tar.gz REPO.tar.gz     offline, two local archives
    srcdiff audit PACKAGE [VERSION]              fetch both from PyPI + GitHub

Exit 0 if nothing suspicious, 1 if something is, 2 on error.
"""
import argparse
import hashlib
import io
import json
import re
import sys
import tarfile
import urllib.error
import urllib.request
import zipfile
from collections import defaultdict

# Extensions that can carry executable behaviour. A divergence in one of these is
# categorically more interesting than a divergence in a README.
CODE_EXT = {
    ".py", ".pyx", ".pxd", ".c", ".h", ".cc", ".cpp", ".hpp", ".rs", ".go",
    ".sh", ".bash", ".zsh", ".pl", ".rb", ".js", ".ts", ".m4", ".am", ".ac",
    ".cmake", ".mk", ".so", ".dll", ".dylib", ".pyd", ".bat", ".ps1",
}

# Files a build legitimately generates into an sdist. Present here, absent from
# the repo, and that is expected rather than alarming.
GENERATED = [
    re.compile(r"^PKG-INFO$"),
    re.compile(r"\.egg-info/"),
    re.compile(r"^setup\.py$"),              # often generated by flit/hatch/pdm
    re.compile(r"_version\.py$"),            # setuptools-scm
    re.compile(r"^(configure|config\.guess|config\.sub|aclocal\.m4|ltmain\.sh)$"),
    re.compile(r"Makefile\.in$"),
    re.compile(r"\.pyc$"),
    re.compile(r"^\._"),                     # macOS resource forks
]

# Things routinely excluded from an sdist. Present in the repo, absent from the
# artifact, which tells us nothing.
REPO_ONLY_OK = [
    re.compile(r"^\.github/"),
    re.compile(r"^\.gitignore$"),
    re.compile(r"^\.gitattributes$"),
    re.compile(r"^\.pre-commit-config\.yaml$"),
    re.compile(r"^(tests?|docs?|examples?|benchmarks?)/"),
    re.compile(r"^(tox\.ini|noxfile\.py|\.travis\.yml|\.readthedocs\.ya?ml)$"),
    re.compile(r"^Makefile$"),
    re.compile(r"^CONTRIBUTING"),
]


def is_code(path):
    dot = path.rfind(".")
    return dot >= 0 and path[dot:].lower() in CODE_EXT


def matches_any(path, patterns):
    return any(p.search(path) for p in patterns)


def strip_root(names):
    """Archives wrap everything in one directory, and the two sides name it
    differently (pkg-1.2.3 vs repo-1.2.3). Drop it so paths are comparable."""
    roots = {n.split("/", 1)[0] for n in names if "/" in n}
    if len(roots) != 1:
        return None                  # no single root: compare paths as-is
    return roots.pop()


def read_archive(path_or_bytes, label):
    """Returns {relative_path: content_bytes} for a .tar.gz, .tar, or .zip/.whl."""
    if isinstance(path_or_bytes, bytes):
        data = path_or_bytes
    else:
        with open(path_or_bytes, "rb") as fh:
            data = fh.read()

    entries = {}
    if data[:2] == b"PK":
        with zipfile.ZipFile(io.BytesIO(data)) as zf:
            for info in zf.infolist():
                if info.is_dir():
                    continue
                entries[info.filename] = zf.read(info)
    else:
        mode = "r:gz" if data[:2] == b"\x1f\x8b" else "r:*"
        with tarfile.open(fileobj=io.BytesIO(data), mode=mode) as tf:
            for member in tf.getmembers():
                if not member.isfile():
                    continue
                fh = tf.extractfile(member)
                if fh is None:
                    continue
                entries[member.name] = fh.read()

    if not entries:
        raise SystemExit(f"srcdiff: {label} contains no files")

    root = strip_root(entries.keys())
    if root:
        out = {}
        for name, content in entries.items():
            rel = name[len(root) + 1:] if name.startswith(root + "/") else name
            if rel:
                out[rel] = content
        return out
    return entries


def sha(data):
    return hashlib.sha256(data).hexdigest()


def eol_equal(a, b):
    """True if the two differ only in line endings."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def classify(artifact, repo):
    """Compare two {path: bytes} maps and bucket every difference by severity.

    HIGH is the xz shape: code present in the published artifact that is absent
    from the repository, and not something a build is known to generate.
    """
    findings = defaultdict(list)

    for path in sorted(set(artifact) - set(repo)):
        if matches_any(path, GENERATED):
            findings["generated"].append(path)
        elif is_code(path):
            findings["HIGH"].append(path)
        else:
            findings["artifact-only-data"].append(path)

    for path in sorted(set(repo) - set(artifact)):
        if matches_any(path, REPO_ONLY_OK):
            findings["repo-only-expected"].append(path)
        else:
            findings["repo-only"].append(path)

    for path in sorted(set(artifact) & set(repo)):
        a, b = artifact[path], repo[path]
        if a == b:
            continue
        if matches_any(path, GENERATED):
            findings["generated-differs"].append(path)
        elif eol_equal(a, b):
            findings["eol-only"].append(path)
        elif is_code(path):
            findings["MEDIUM"].append(f"{path}  ({sha(b)[:12]} -> {sha(a)[:12]})")
        else:
            findings["data-differs"].append(path)

    return findings


SEVERITY_ORDER = [
    ("HIGH", "code in the artifact that is NOT in the repository"),
    ("MEDIUM", "code present in both, but with different content"),
    ("repo-only", "in the repository but missing from the artifact"),
    ("data-differs", "non-code content differs"),
    ("artifact-only-data", "non-code files only in the artifact"),
    ("eol-only", "differ only in line endings"),
    ("generated", "only in the artifact, but known to be generated"),
    ("generated-differs", "differs, but known to be generated"),
    ("repo-only-expected", "only in the repository, routinely excluded"),
]


def report(findings, verbose=False):
    quiet = {"generated", "generated-differs", "repo-only-expected", "eol-only"}
    suspicious = 0

    for key, blurb in SEVERITY_ORDER:
        items = findings.get(key, [])
        if not items:
            continue
        if key in quiet and not verbose:
            print(f"  {len(items):4d}  {key}: {blurb} (suppressed, -v to list)")
            continue
        print(f"\n  {key}: {blurb}")
        for item in items[:40]:
            print(f"      {item}")
        if len(items) > 40:
            print(f"      ... and {len(items) - 40} more")

    suspicious = len(findings.get("HIGH", [])) + len(findings.get("MEDIUM", []))
    print()
    if suspicious:
        print(f"{suspicious} suspicious finding(s). HIGH entries are the xz shape:"
              " shipped code with no counterpart in the repository.")
    else:
        print("No suspicious findings. Divergence is all generated or expected.")
    return 1 if suspicious else 0


# ------------------------------------------------------------------ network side

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "srcdiff/0.1"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def pypi_metadata(package, version=None):
    url = (f"https://pypi.org/pypi/{package}/json" if version is None
           else f"https://pypi.org/pypi/{package}/{version}/json")
    return json.loads(fetch(url))


def find_sdist(meta):
    for entry in meta["urls"]:
        if entry["packagetype"] == "sdist":
            return entry["url"], entry["filename"]
    raise SystemExit("srcdiff: this release has no sdist, only wheels")


GITHUB_RE = re.compile(r"github\.com/([^/\s]+)/([^/\s#?]+)", re.I)

# github.com paths that are not repositories. Without this, a funding link like
# github.com/sponsors/hynek parses as owner="sponsors", repo="hynek" -- which is
# exactly what the first live run did.
NOT_AN_OWNER = {
    "sponsors", "orgs", "users", "apps", "marketplace", "features", "about",
    "pricing", "enterprise", "collections", "topics", "settings", "login",
}

# project_urls keys that actually point at source, most trustworthy first.
SOURCE_KEY_RE = re.compile(r"source|repo|code|git|tracker|homepage|home", re.I)


def find_github(meta):
    info = meta["info"]
    project_urls = info.get("project_urls") or {}

    # Try the keys that claim to be source before falling back to anything else,
    # so a Funding entry cannot win over a Source entry.
    ordered = [v for k, v in project_urls.items() if SOURCE_KEY_RE.search(k)]
    ordered += [v for k, v in project_urls.items() if not SOURCE_KEY_RE.search(k)]
    ordered += [info.get("home_page") or "", info.get("download_url") or ""]

    for url in ordered:
        m = GITHUB_RE.search(url or "")
        if not m:
            continue
        owner, repo = m.group(1), m.group(2).removesuffix(".git")
        if owner.lower() in NOT_AN_OWNER:
            continue
        return owner, repo
    raise SystemExit("srcdiff: no GitHub repository declared in the metadata")


def fetch_tag(owner, repo, version):
    """Tag spelling is a guess; try the common ones and say which one worked."""
    for tag in (f"v{version}", version, f"release-{version}", f"{repo}-{version}"):
        url = f"https://codeload.github.com/{owner}/{repo}/tar.gz/refs/tags/{tag}"
        try:
            data = fetch(url)
            return data, tag
        except urllib.error.HTTPError as exc:
            if exc.code != 404:
                raise
    raise SystemExit(f"srcdiff: no tag found for {version} in {owner}/{repo} "
                     f"(tried v{version}, {version}, release-{version})")


def cmd_audit(args):
    meta = pypi_metadata(args.package, args.version)
    version = meta["info"]["version"]
    sdist_url, sdist_name = find_sdist(meta)
    owner, repo = find_github(meta)

    print(f"package : {args.package} {version}")
    print(f"sdist   : {sdist_name}")
    print(f"repo    : github.com/{owner}/{repo}")

    sdist_bytes = fetch(sdist_url)
    repo_bytes, tag = fetch_tag(owner, repo, version)
    print(f"tag     : {tag}\n")

    artifact = read_archive(sdist_bytes, "sdist")
    source = read_archive(repo_bytes, "repo tarball")
    print(f"{len(artifact)} files in the sdist, {len(source)} in the repo at {tag}")
    return report(classify(artifact, source), args.verbose)


def cmd_compare(args):
    artifact = read_archive(args.artifact, args.artifact)
    source = read_archive(args.repo, args.repo)
    print(f"{len(artifact)} files in the artifact, {len(source)} in the repo")
    return report(classify(artifact, source), args.verbose)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="list suppressed categories instead of counting them")
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("compare", help="compare two local archives, no network")
    c.add_argument("artifact")
    c.add_argument("repo")
    c.set_defaults(fn=cmd_compare)

    a = sub.add_parser("audit", help="fetch an sdist and its git tag, then compare")
    a.add_argument("package")
    a.add_argument("version", nargs="?")
    a.set_defaults(fn=cmd_audit)

    args = ap.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
