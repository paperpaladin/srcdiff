#!/usr/bin/env python3
"""srcdiff -- find code in a published artifact that was never in the repository.

This is the xz-utils shape: the release tarball contained build machinery that
was not in the git tree, and nobody was diffing the two. The check is simple to
state and annoying to do well, because legitimate divergence is the *norm* --
generated files, vendored dependencies, packaging metadata, excluded tests. The
work is suppressing that without suppressing the one finding that matters.

Standard library only. No requests, no packaging, no diffoscope.

    srcdiff compare SDIST.tar.gz REPO.tar.gz     offline, two local archives
    srcdiff audit PACKAGE [VERSION]              fetch both from PyPI + GitHub

Exit 0 if nothing suspicious, 1 if something is, 2 on error.
"""
import argparse
import hashlib
import os
import io
import json
import re
import sys
import tarfile
import urllib.error
import urllib.request
import zipfile
from collections import defaultdict

# Extensions that can carry executable behaviour. A divergence in one of these is
# categorically more interesting than a divergence in a README.
CODE_EXT = {
    ".py", ".pyx", ".pxd", ".c", ".h", ".cc", ".cpp", ".hpp", ".rs", ".go",
    ".sh", ".bash", ".zsh", ".pl", ".rb", ".js", ".ts", ".m4", ".am", ".ac",
    ".cmake", ".mk", ".so", ".dll", ".dylib", ".pyd", ".bat", ".ps1",
}

# Where an autotools build machine keeps the canonical copies of the m4 macros and
# helper scripts that libtoolize/gettextize/autoreconf vendor INTO a release
# tarball. These arrive from the build host, not from the project's git, so the
# project's repo is the wrong oracle for them -- see VENDORED_DIRS use below.
VENDOR_SOURCE_DIRS = [
    "/usr/share/aclocal",
    "/usr/share/gettext/m4",
    "/usr/share/libtool/build-aux",
    "/usr/share/automake-1.17",
    "/usr/share/automake-1.16",
    "/usr/local/share/aclocal",
]

# Paths inside an artifact where vendored build machinery lives.
VENDORED_RE = re.compile(r"^(m4|build-aux|config|autoconf)/|^(ltmain\.sh|config\.(guess|sub)|install-sh|compile|depcomp|missing|ar-lib|test-driver|py-compile)$")


# Autotools macros carry an upstream version marker. gettext writes
# "# gettext.m4 serial 72 (gettext-0.21.1)"; libtool writes "# serial 59 LT_INIT".
# It is the only thing in the file that says which upstream revision it is.
# m4 macros: "# gettext.m4 serial 72 (gettext-0.21.1)" or "# serial 59 LT_INIT".
SERIAL_RE = re.compile(rb"^#\s*(?:[\w.~-]+\.m4\s*\n?#?\s*)?serial\s+(\d+)", re.M | re.I)

# build-aux helper scripts carry a date or a release instead of a serial:
#   scriptversion=2018-03-07.03     (automake)
#   timestamp='2022-01-09'         (config.guess / config.sub)
#   VERSION=2.4.7.4-1ec8f-dirty    (ltmain.sh)
SCRIPT_VER_RE = re.compile(
    rb"""^\s*(?:scriptversion|timestamp|VERSION)\s*=\s*["']?([\w.:+~-]+)""",
    re.M)


def version_marker(data):
    """Whatever the file says about which upstream revision it is, or None.

    This is the only in-band statement of provenance these files carry, and the
    whole vendored check turns on it: a file from a DIFFERENT upstream release is
    expected to differ, a file claiming the SAME release is not.
    """
    m = SERIAL_RE.search(data)
    if m:
        return "serial " + m.group(1).decode()
    m = SCRIPT_VER_RE.search(data)
    if m:
        return m.group(1).decode()
    return None


# A copyright year range is bumped on every upstream release WITHOUT bumping the
# macro serial, so two copies of "serial 6" can differ by exactly this and nothing
# else. Normalising it is narrow on purpose: only digits and dashes, only on a line
# that says Copyright. Anything an attacker added would survive this.
COPYRIGHT_YEARS_RE = re.compile(rb"(?i)(copyright[^\n]*?)([0-9]{4}(?:[-,0-9 ]*[0-9]{4})?)")


def copyright_normalised(data):
    return COPYRIGHT_YEARS_RE.sub(rb"\1<YEARS>", data)


def canonical_copy(path):
    """The build host's own copy of a vendored file, if it has one.

    This is the second oracle, and the xz-utils backdoor is exactly why it has to
    exist. build-to-host.m4 is a REAL gettext macro -- it ships in
    /usr/share/aclocal on any machine with gettext installed. The attacker did not
    invent a filename; they shipped a MODIFIED copy of a legitimate one. So a
    name-based allowlist cannot separate the two, and the project's git repo never
    contained either version. Only the canonical upstream copy can tell them apart.
    """
    if not VENDORED_RE.search(path):
        return None
    base = path.rsplit("/", 1)[-1]
    for d in VENDOR_SOURCE_DIRS:
        cand = os.path.join(d, base)
        if os.path.isfile(cand):
            return cand
    return None


# Files a build legitimately generates into an sdist. Present here, absent from
# the repo, and that is expected rather than alarming.
GENERATED = [
    re.compile(r"^PKG-INFO$"),
    re.compile(r"\.egg-info/"),
    re.compile(r"^setup\.py$"),              # often generated by flit/hatch/pdm
    re.compile(r"_version\.py$"),            # setuptools-scm
    re.compile(r"^(configure|config\.guess|config\.sub|aclocal\.m4|ltmain\.sh)$"),
    re.compile(r"Makefile\.in$"),
    re.compile(r"\.pyc$"),
    re.compile(r"^\._"),                     # macOS resource forks
]

# Things routinely excluded from an sdist. Present in the repo, absent from the
# artifact, which tells us nothing.
REPO_ONLY_OK = [
    re.compile(r"^\.github/"),
    re.compile(r"^\.gitignore$"),
    re.compile(r"^\.gitattributes$"),
    re.compile(r"^\.pre-commit-config\.yaml$"),
    re.compile(r"^(tests?|docs?|examples?|benchmarks?)/"),
    re.compile(r"^(tox\.ini|noxfile\.py|\.travis\.yml|\.readthedocs\.ya?ml)$"),
    re.compile(r"^Makefile$"),
    re.compile(r"^CONTRIBUTING"),
]


def is_code(path):
    dot = path.rfind(".")
    return dot >= 0 and path[dot:].lower() in CODE_EXT


def matches_any(path, patterns):
    return any(p.search(path) for p in patterns)


def strip_root(names):
    """Archives wrap everything in one directory, and the two sides name it
    differently (pkg-1.2.3 vs repo-1.2.3). Drop it so paths are comparable."""
    roots = {n.split("/", 1)[0] for n in names if "/" in n}
    if len(roots) != 1:
        return None                  # no single root: compare paths as-is
    return roots.pop()


def read_archive(path_or_bytes, label):
    """Returns {relative_path: content_bytes} for a .tar.gz, .tar, or .zip/.whl."""
    if isinstance(path_or_bytes, bytes):
        data = path_or_bytes
    else:
        with open(path_or_bytes, "rb") as fh:
            data = fh.read()

    # A file that is not an archive at all is an error, not a crash. Handing
    # this function an ordinary text file used to raise tarfile.ReadError and
    # print a traceback, exiting 1 -- the same status as "found something
    # suspicious", for a tool whose exit code is meant to be readable from CI.
    # ReadError and BadZipFile are not OSError subclasses, so a handler at the
    # entry point does not reach them, and the message is better here anyway
    # because it can name which of the two archives was unreadable.
    entries = {}
    try:
        if data[:2] == b"PK":
            with zipfile.ZipFile(io.BytesIO(data)) as zf:
                for info in zf.infolist():
                    if info.is_dir():
                        continue
                    entries[info.filename] = zf.read(info)
        else:
            mode = "r:gz" if data[:2] == b"\x1f\x8b" else "r:*"
            with tarfile.open(fileobj=io.BytesIO(data), mode=mode) as tf:
                for member in tf.getmembers():
                    if not member.isfile():
                        continue
                    fh = tf.extractfile(member)
                    if fh is None:
                        continue
                    entries[member.name] = fh.read()
    except (tarfile.TarError, zipfile.BadZipFile) as e:
        raise SystemExit(f"srcdiff: {label} is not a readable archive: {e}")

    if not entries:
        raise SystemExit(f"srcdiff: {label} contains no files")

    root = strip_root(entries.keys())
    if root:
        out = {}
        for name, content in entries.items():
            rel = name[len(root) + 1:] if name.startswith(root + "/") else name
            if rel:
                out[rel] = content
        return out
    return entries


def sha(data):
    return hashlib.sha256(data).hexdigest()


def eol_equal(a, b):
    """True if the two differ only in line endings."""
    return a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def classify(artifact, repo):
    """Compare two {path: bytes} maps and bucket every difference by severity.

    HIGH is the xz shape: code present in the published artifact that is absent
    from the repository, and not something a build is known to generate.
    """
    findings = defaultdict(list)

    for path in sorted(set(artifact) - set(repo)):
        if matches_any(path, GENERATED):
            findings["generated"].append(path)
            continue

        # Vendored build machinery: the repo is the wrong oracle. Ask the build
        # host's canonical copy instead.
        canon = canonical_copy(path)
        if canon is not None:
            try:
                with open(canon, "rb") as fh:
                    want = fh.read()
            except OSError:
                want = None
            if want is not None:
                got = artifact[path]
                if want == got:
                    findings["vendored-verified"].append(f"{path}  (matches {canon})")
                    continue

                # It differs -- but an autotools macro also legitimately differs
                # between upstream releases, and the build host here is almost never
                # running the version the release was cut with. The serial is what
                # separates the two cases.
                s_got, s_want = version_marker(got), version_marker(want)
                if s_got and s_want and s_got != s_want:
                    findings["vendored-version-skew"].append(
                        f"{path}  {s_got} shipped vs {s_want} on this host")
                    continue

                # Same declared revision. Before calling it suspicious, rule out the
                # one difference upstream makes without bumping the marker.
                if copyright_normalised(got) == copyright_normalised(want):
                    findings["vendored-version-skew"].append(
                        f"{path}  {s_got or 'no marker'}, differs only in a "
                        f"copyright year range")
                    continue

                # Same declared version, different bytes. THE XZ SIGNATURE: a
                # legitimate vendored filename, absent from the repo, claiming to be
                # a revision it is not byte-identical to. A file that was modified
                # in place does not advertise itself as a new release.
                detail = (s_got if s_got else "no version marker")
                findings["HIGH-VENDORED"].append(
                    f"{path}  {detail}, same as host, but content differs "
                    f"({len(want)}B canonical vs {len(got)}B shipped, "
                    f"{sha(want)[:12]} vs {sha(got)[:12]})")
                continue
            findings["vendored-unverifiable"].append(path)
            continue

        if is_code(path):
            findings["HIGH"].append(path)
        else:
            findings["artifact-only-data"].append(path)

    for path in sorted(set(repo) - set(artifact)):
        if matches_any(path, REPO_ONLY_OK):
            findings["repo-only-expected"].append(path)
        else:
            findings["repo-only"].append(path)

    for path in sorted(set(artifact) & set(repo)):
        a, b = artifact[path], repo[path]
        if a == b:
            continue
        if matches_any(path, GENERATED):
            findings["generated-differs"].append(path)
        elif eol_equal(a, b):
            findings["eol-only"].append(path)
        elif is_code(path):
            findings["MEDIUM"].append(f"{path}  ({sha(b)[:12]} -> {sha(a)[:12]})")
        else:
            findings["data-differs"].append(path)

    return findings


SEVERITY_ORDER = [
    ("HIGH-VENDORED",
     "vendored build machinery that does NOT match its canonical upstream copy "
     "-- this is the exact xz-utils signature"),
    ("HIGH", "code in the artifact that is NOT in the repository"),
    ("MEDIUM", "code present in both, but with different content"),
    ("repo-only", "in the repository but missing from the artifact"),
    ("data-differs", "non-code content differs"),
    ("artifact-only-data", "non-code files only in the artifact"),
    ("eol-only", "differ only in line endings"),
    ("generated", "only in the artifact, but known to be generated"),
    ("generated-differs", "differs, but known to be generated"),
    ("repo-only-expected", "only in the repository, routinely excluded"),
    ("vendored-verified", "vendored build machinery, byte-identical to upstream"),
    ("vendored-version-skew",
     "vendored build machinery from a different upstream release than this host has"),
    ("vendored-unverifiable",
     "vendored build machinery with no canonical copy on this host to compare against"),
]


def report(findings, verbose=False):
    quiet = {"generated", "generated-differs", "repo-only-expected", "eol-only",
             "vendored-verified", "vendored-version-skew"}
    suspicious = 0

    for key, blurb in SEVERITY_ORDER:
        items = findings.get(key, [])
        if not items:
            continue
        if key in quiet and not verbose:
            print(f"  {len(items):4d}  {key}: {blurb} (suppressed, -v to list)")
            continue
        print(f"\n  {key}: {blurb}")
        for item in items[:40]:
            print(f"      {item}")
        if len(items) > 40:
            print(f"      ... and {len(items) - 40} more")

    suspicious = (len(findings.get("HIGH-VENDORED", []))
                  + len(findings.get("HIGH", []))
                  + len(findings.get("MEDIUM", [])))
    print()
    unverifiable = len(findings.get("vendored-unverifiable", []))
    if suspicious:
        print(f"{suspicious} suspicious finding(s). HIGH-VENDORED is the xz shape:"
              " a legitimate vendored filename whose content does not match the"
              " upstream it claims to be.")
    else:
        print("No suspicious findings. Divergence is all generated, vendored-verified,"
              " or expected.")
    if unverifiable:
        print(f"{unverifiable} vendored file(s) could not be checked: no canonical copy"
              f" on this host. Install the matching autotools/gettext version to close"
              f" that gap -- it is where an xz-shaped file would hide.")
    return 1 if suspicious else 0


# ------------------------------------------------------------------ network side

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "srcdiff/0.1"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def pypi_metadata(package, version=None):
    url = (f"https://pypi.org/pypi/{package}/json" if version is None
           else f"https://pypi.org/pypi/{package}/{version}/json")
    return json.loads(fetch(url))


def find_sdist(meta):
    for entry in meta["urls"]:
        if entry["packagetype"] == "sdist":
            return entry["url"], entry["filename"]
    raise SystemExit("srcdiff: this release has no sdist, only wheels")


GITHUB_RE = re.compile(r"github\.com/([^/\s]+)/([^/\s#?]+)", re.I)

# github.com paths that are not repositories. Without this, a funding link like
# github.com/sponsors/hynek parses as owner="sponsors", repo="hynek" -- which is
# exactly what the first live run did.
NOT_AN_OWNER = {
    "sponsors", "orgs", "users", "apps", "marketplace", "features", "about",
    "pricing", "enterprise", "collections", "topics", "settings", "login",
}

# project_urls keys that actually point at source, most trustworthy first.
SOURCE_KEY_RE = re.compile(r"source|repo|code|git|tracker|homepage|home", re.I)


def find_github(meta):
    info = meta["info"]
    project_urls = info.get("project_urls") or {}

    # Try the keys that claim to be source before falling back to anything else,
    # so a Funding entry cannot win over a Source entry.
    ordered = [v for k, v in project_urls.items() if SOURCE_KEY_RE.search(k)]
    ordered += [v for k, v in project_urls.items() if not SOURCE_KEY_RE.search(k)]
    ordered += [info.get("home_page") or "", info.get("download_url") or ""]

    for url in ordered:
        m = GITHUB_RE.search(url or "")
        if not m:
            continue
        owner, repo = m.group(1), m.group(2).removesuffix(".git")
        if owner.lower() in NOT_AN_OWNER:
            continue
        return owner, repo
    raise SystemExit("srcdiff: no GitHub repository declared in the metadata")


def fetch_tag(owner, repo, version):
    """Tag spelling is a guess; try the common ones and say which one worked."""
    for tag in (f"v{version}", version, f"release-{version}", f"{repo}-{version}"):
        url = f"https://codeload.github.com/{owner}/{repo}/tar.gz/refs/tags/{tag}"
        try:
            data = fetch(url)
            return data, tag
        except urllib.error.HTTPError as exc:
            if exc.code != 404:
                raise
    raise SystemExit(f"srcdiff: no tag found for {version} in {owner}/{repo} "
                     f"(tried v{version}, {version}, release-{version}, "
                     f"{repo}-{version})")


def cmd_audit(args):
    meta = pypi_metadata(args.package, args.version)
    version = meta["info"]["version"]
    sdist_url, sdist_name = find_sdist(meta)
    owner, repo = find_github(meta)

    print(f"package : {args.package} {version}")
    print(f"sdist   : {sdist_name}")
    print(f"repo    : github.com/{owner}/{repo}")

    sdist_bytes = fetch(sdist_url)
    repo_bytes, tag = fetch_tag(owner, repo, version)
    print(f"tag     : {tag}\n")

    artifact = read_archive(sdist_bytes, "sdist")
    source = read_archive(repo_bytes, "repo tarball")
    print(f"{len(artifact)} files in the sdist, {len(source)} in the repo at {tag}")
    return report(classify(artifact, source), args.verbose)


def cmd_compare(args):
    artifact = read_archive(args.artifact, args.artifact)
    source = read_archive(args.repo, args.repo)
    print(f"{len(artifact)} files in the artifact, {len(source)} in the repo")
    return report(classify(artifact, source), args.verbose)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="list suppressed categories instead of counting them")
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("compare", help="compare two local archives, no network")
    c.add_argument("artifact")
    c.add_argument("repo")
    c.set_defaults(fn=cmd_compare)

    a = sub.add_parser("audit", help="fetch an sdist and its git tag, then compare")
    a.add_argument("package")
    a.add_argument("version", nargs="?")
    a.set_defaults(fn=cmd_audit)

    args = ap.parse_args()
    return args.fn(args)


# Exit 2 means "could not answer", and it has to be distinct from exit 1,
# "answered and found something". README.md and the docstring above have both
# documented 2 since the beginning and no path produced it: every error site
# raises SystemExit("srcdiff: ..."), which Python exits 1 for, and main()
# returns only 0 or 1. So a missing sdist, an undeclared repository and a real
# finding were one status -- in a tool whose PLAN calls the exit code the
# contract that makes it "usable from CI without parsing output".
#
# An unreadable path was worse than that: `compare /nonexistent /nonexistent`
# printed a traceback and exited 1, so a typo in a CI invocation read as a
# supply-chain finding.
if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit as e:
        # A string argument is one of our own diagnostics; an int is a status
        # main() chose, and argparse's own exits (2 for a usage error) pass
        # through unchanged.
        if isinstance(e.code, str):
            print(e.code, file=sys.stderr)
            sys.exit(2)
        raise
    except OSError as e:
        print("srcdiff: %s" % e, file=sys.stderr)
        sys.exit(2)
    except KeyboardInterrupt:
        sys.exit(130)
